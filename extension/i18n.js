  /** The supported language for a code like 'fa', 'ru-RU' or 'en_US'; '' when there is none. */
  function norm(code) {
    const base = String(code || '')
      .toLowerCase()
      .slice(0, 2)
    return DICT[base] ? base : ''
  }

  root.LightningI18n = {
    dict: DICT,
    norm,
    /** Lightning's own language first, then the browser's, then English. */
    pick: (lightning, ui) => norm(lightning) || norm(ui) || 'en',
    dir: (lang) => (lang === 'fa' ? 'rtl' : 'ltr'),
    t(lang, key, vars) {
      let text = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key
      for (const name in vars || {}) text = text.split('{' + name + '}').join(String(vars[name]))
      return text
    }
  }
